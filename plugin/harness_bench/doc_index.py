"""Generate a repository's agent index: commands, layout and documents.

An agent that has to list folders and open documents to find its way reads far
more than it needs. A hand-written map goes stale, and a stale map is worse than
none. So this index is generated from what git tracks, with nothing typed by
hand, and `--check` fails when the committed copy no longer matches, for CI.

The output is deterministic for a given checkout: no generation time, sorted
everywhere. It holds no dates: a last-changed date from git moves with the very commit that
refreshes the index, so the index could never be current.
"""
from __future__ import annotations

import json
from pathlib import Path, PurePosixPath
import re
import subprocess
from collections import Counter

HEADER = "<!-- Generated by harness-state index. Do not edit by hand. -->"
HISTORICAL = re.compile(r"(^|/)(_history|history|archive|_archive|old)(/|$)", re.I)
STATUS = [("superseded", re.compile(r"\bSUPERSEDED\b|\bsuperseded by\b", re.I)),
          ("draft", re.compile(r"\bDRAFT\b")),
          ("authoritative", re.compile(r"\bAUTHORITATIVE\b"))]


def git(repo, *args):
    p = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True)
    if p.returncode:
        raise ValueError(p.stderr.strip())
    return p.stdout


def tracked(repo):
    return sorted(f for f in git(repo, "ls-files").splitlines() if "node_modules/" not in f)


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def clip(text, limit):
    return text if len(text) <= limit else text[:limit - 1].rstrip() + "\u2026"


def doc_row(repo, path):
    text = (Path(repo) / path).read_text(errors="replace")
    lines = text.splitlines()
    title = next((l.lstrip("#").strip() for l in lines if l.startswith("# ")), PurePosixPath(path).stem)
    head = "\n".join(lines[:20])
    status = "historical" if HISTORICAL.search(path) else next((s for s, rx in STATUS if rx.search(head)), "")
    if not status and "_handoff" in path:
        status = "handoff"
    sections = [l.lstrip("#").strip() for l in lines if l.startswith("## ")]
    return {"path": path, "title": clip(title, 70), "status": status, "words": len(text.split()),
            "sections": clip("; ".join(sections), 140)}


def doc_order(row):
    rank = {"": 1, "authoritative": 1, "draft": 2, "handoff": 3, "superseded": 4, "historical": 5}
    top = 0 if "/" not in row["path"] else 1
    return (top if row["status"] != "historical" else 2, rank.get(row["status"], 1), row["path"])


def commands(repo, files):
    rows = []
    for f in files:
        if PurePosixPath(f).name != "package.json":
            continue
        try:
            scripts = json.loads((Path(repo) / f).read_text()).get("scripts") or {}
        except (ValueError, OSError):
            continue
        where = str(PurePosixPath(f).parent)
        for name in sorted(scripts):
            run = f"npm run {name}" if where == "." else f"npm run {name} --workspace {where}"
            rows.append((run, scripts[name]))
    return rows


def layout(files):
    """Folders two levels deep and the kinds of file in each. No counts: adding a file of a kind
    the folder already holds must not make the index stale."""
    kinds = {}
    for f in files:
        parts = PurePosixPath(f).parts
        if len(parts) == 1:
            continue
        key = parts[0] if len(parts) == 2 else "/".join(parts[:2])
        kinds.setdefault(key, set()).add(PurePosixPath(f).suffix or PurePosixPath(f).name)
    return [(key + "/", ", ".join(sorted(kinds[key]))) for key in sorted(kinds)]


def render(repo, command="harness-state index", exclude=None):
    # The index never lists itself: its own row would change on every refresh.
    files = [f for f in tracked(repo) if f != exclude]
    docs = sorted((doc_row(repo, f) for f in files if f.endswith(".md")), key=doc_order)
    out = [HEADER, "", "# Repository index", "",
           f"Generated from the files git tracks. To refresh: `{command}`. Use it to go straight to the",
           "right file; open a document only for the sections you need.", ""]
    cmds = commands(repo, files)
    if cmds:
        out += ["## Commands", "", "| Command | Runs |", "|---|---|"]
        out += [f"| `{cell(c)}` | `{cell(r)}` |" for c, r in cmds] + [""]
    out += ["## Layout", "", "| Folder | Holds |", "|---|---|"]
    out += [f"| `{cell(k)}` | {cell(t)} |" for k, t in layout(files)] + [""]
    out += ["## Documents", "",
            "Status comes from the document's own header (AUTHORITATIVE, DRAFT, SUPERSEDED) or its folder",
            "(historical, handoff). Historical documents are listed last; cite them only where an instruction",
            "points to a named section.", "",
            "| Document | Title | Status | Words | Sections |", "|---|---|---|---:|---|"]
    out += [f"| `{cell(d['path'])}` | {cell(d['title'])} | {d['status'] or 'current'} | {d['words']:,} | "
            f"{cell(d['sections'])} |" for d in docs]
    return "\n".join(out) + "\n"


def write_or_check(repo, target, check=False, command="harness-state index"):
    target = Path(repo) / target
    text = render(repo, command, exclude=str(target.relative_to(Path(repo))))
    if check:
        current = target.read_text() if target.exists() else ""
        return current == text
    target.write_text(text)
    return True
